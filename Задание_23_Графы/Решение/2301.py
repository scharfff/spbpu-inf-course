"""
Демоверсия ЕГЭ 2027 (проект ФИПИ), задание 23. Файл: 2301.txt

В текстовом файле содержится описание ациклического ориентированного
взвешенного графа. В каждой строке файла записаны два натуральных числа
(L, M) и одно положительное вещественное число (W). L и M – номера
вершин графа, W – вес ребра, ведущего из вершины L в вершину M.
Две вершины графа не могут быть соединены более чем одним ребром.

Найдите и запишите в ответе целую часть длины кратчайшего пути из
вершины с номером 1 в вершину с номером 100. Существование хотя бы
одного такого пути гарантируется.

Вершины графа могут быть пронумерованы не подряд. L ≤ 1000, M ≤ 1000;
W ≤ 10 000. Числа в строках разделены произвольным ненулевым
количеством пробелов и/или табуляций.

Ответ: 10971
"""

from functools import lru_cache

# входящие рёбра: into[M] = [(L, W), ...]
into = {}
for line in open('2301.txt'):
    if not line.split():
        continue
    l, m, w = line.split()          # split() без аргументов съедает любые пробелы и табы
    into.setdefault(int(m), []).append((int(l), float(w)))


@lru_cache(None)
def dist(v):
    """Длина кратчайшего пути из вершины 1 в вершину v."""
    if v == 1:
        return 0
    # граф ациклический, поэтому рекурсия не зациклится
    return min((dist(u) + w for u, w in into.get(v, [])), default=float('inf'))


print(int(dist(100)))
