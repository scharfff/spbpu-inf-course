"""
ФИПИ. Демоверсия 2027, задание 26. Журнал работы сервера

Сервер принимает запросы и кладет данные каждого запроса
в раздел памяти вместимостью K Кбайт. Если очередной запрос
в раздел не помещается, сервер сначала делает резервную копию
всего накопленного, очищает раздел и только потом кладет туда запрос.

В первой строке файла записаны N (число строк журнала) и K.
В каждой следующей строке записаны время запроса в формате ЧЧ:ММ:СС,
номер клиента и объем данных в Кбайт (объем всегда меньше K).

Найдите номер клиента, который передал больше всего данных,
и сумму объемов двух самых больших резервных копий,
сделанных не позднее 11:59:59.

Ответ: 7040 52204
"""

f = open('2601.txt')                    # открываем файл
n, k = map(int, f.readline().split())   # шапка, число строк и вместимость раздела

total = {}        # клиент и сколько он передал за весь журнал
used = 0          # сколько сейчас занято в разделе
copies = []       # объемы копий, сделанных не позднее 11:59:59

for s in f:
    t, c, v = s.split()           # время, номер клиента, объем
    c, v = int(c), int(v)
    total[c] = total.get(c, 0) + v
    if used + v > k:              # запрос не помещается
        if t <= '11:59:59':       # время сравниваем как строки
            copies.append(used)   # в копию уходит накопленное
        used = 0                  # раздел очищен
    used += v                     # кладем запрос в раздел

best = max(total, key=total.get)  # клиент с наибольшей суммой
copies.sort()                     # два самых больших объема стоят в конце
print(best, copies[-1] + copies[-2])
