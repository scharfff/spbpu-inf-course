"""
Тренировочная задача на второй тип задания 23 (подсчёт путей). Файл: 2302.txt
(тот же граф, что в демоверсии ЕГЭ 2027).

В текстовом файле содержится описание ациклического ориентированного
взвешенного графа. В каждой строке файла записаны два натуральных числа
(L, M) и одно положительное вещественное число (W): ребро из L в M с весом W.

Определите количество различных путей из вершины с номером 1
в вершину с номером 100. Веса рёбер в этой задаче не нужны.

Ответ: 2033652335
"""

from functools import lru_cache

# входящие рёбра: into[M] = [L, ...]
into = {}
for line in open('2302.txt'):
    if not line.split():
        continue
    l, m, w = line.split()
    into.setdefault(int(m), []).append(int(l))


@lru_cache(None)
def paths(v):
    """Количество путей из вершины 1 в вершину v."""
    if v == 1:
        return 1
    # как в задании 13: число путей в v = сумма путей во все вершины, из которых есть ребро в v
    return sum(paths(u) for u in into.get(v, []))


print(paths(100))
