"""
Демоверсия ЕГЭ 2027, задание 12 (исполнитель МТ, машина Тьюринга)

На ленте в соседних ячейках записано двоичное представление числа 2025
без ведущих нулей. Ячейки справа и слева от последовательности заполнены
пустыми символами «λ». В начальный момент времени головка расположена
в ближайшей справа к последовательности ячейке.

Программа работы исполнителя (строка это состояние, в скобках символ под головкой)
q0   (λ) λ, L, q1
q1   (λ) 1, L, q2   (0) 0, L, q1   (1) 1, L, q1
q2   (λ) λ, S, q2

Определите результат выполнения программы.
В ответе запишите получившееся число в десятичной системе счисления.

Ответ: 4073
"""

# Таблица программы. Ключ это пара (состояние, символ под головкой),
# значение это команда (что записать, куда сдвинуться, новое состояние).
# Пустой символ λ записан знаком подчеркивания.
prog = {
    ('q0', '_'): ('_', 'L', 'q1'),
    ('q1', '_'): ('1', 'L', 'q2'),
    ('q1', '0'): ('0', 'L', 'q1'),
    ('q1', '1'): ('1', 'L', 'q1'),
    ('q2', '_'): ('_', 'S', 'q2'),
}

s = list('_' * 3 + bin(2025)[2:] + '_' * 3)  # лента, число и по три пустые ячейки с краев
i = len(s) - 3  # головка в ближайшей ячейке справа от числа
q = 'q0'        # начальное состояние

while True:
    a, d, q = prog[q, s[i]]  # команда для пары (состояние, символ)
    s[i] = a                 # записали символ в текущую ячейку
    if d == 'L': i -= 1      # сдвиг влево
    if d == 'R': i += 1      # сдвиг вправо
    if d == 'S': break       # стоп, программа закончила работу

print(int(''.join(s).strip('_'), 2))  # 4073

# То же самое без симулятора. Программа дописывает единицу слева от числа,
# в записи 2025 одиннадцать цифр, поэтому к числу прибавляется 2 ** 11 = 2048
print(int('1' + bin(2025)[2:], 2))    # 4073
